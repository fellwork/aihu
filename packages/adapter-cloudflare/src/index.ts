import { existsSync, readFileSync } from 'node:fs'
import { relative as relativePath, resolve as resolvePath } from 'node:path'
import type { AdapterContext, AihuAdapter, ServerEntryContext } from '@aihu/app'
// A VALUE import, deliberately — see `generateWranglerToml`. The SSR output
// directory is derived by @aihu/app from the client `build.outDir`, and this
// adapter has to name that directory in the wrangler.toml it writes. Importing
// the derivation is the only way the two cannot drift.
import { ssrOutDirFor } from '@aihu/app'

/**
 * A single route as exposed on AdapterContext.routes. We derive the element
 * type from the context interface so the adapter never takes a direct
 * dependency on @aihu/router. The non-serializable `module()` function is
 * irrelevant at adapt() time and is dropped from the emitted manifest.
 */
type ContextRoute = AdapterContext['routes'][number]

export interface CloudflareAdapterOptions {
  /**
   * Cloudflare Worker name. Used in generated wrangler.toml.
   * Default: value of "name" in the project's package.json, or 'aihu-app'.
   */
  name?: string
  /**
   * Deployment mode.
   * - 'workers': Cloudflare Workers with static assets via env.ASSETS binding
   * - 'pages': Cloudflare Pages (_worker.js convention — same output, different deploy target)
   * Default: 'workers'
   */
  mode?: 'workers' | 'pages'
  /**
   * Whether to write wrangler.toml in the project root if it does not exist.
   * Never overwrites an existing wrangler.toml.
   * Default: true
   */
  generateWrangler?: boolean
  /**
   * Enable SSR + static hybrid mode.
   *
   * When true, the generated `_worker.js` calls your aihu server handler first
   * (SSR routes, API routes, agent-readiness endpoints), then falls back to
   * Cloudflare's ASSETS binding for pre-rendered static files, and finally
   * falls back to `/index.html` for client-side-routed SPA pages.
   *
   * Route priority: SSR handler → ASSETS (CDN edge) → /index.html (SPA shell)
   *
   * Default: false (SPA-only mode, all requests served from ASSETS)
   */
  ssr?: boolean
}

function readPackageJsonName(root: string): string | null {
  const pkgPath = resolvePath(root, 'package.json')
  if (!existsSync(pkgPath)) return null
  try {
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as { name?: string }
    return typeof pkg.name === 'string' ? pkg.name : null
  } catch {
    return null
  }
}

/**
 * The SPA-shell fallback, shared by all three generated worker shapes.
 *
 * ## The `catch` was dead code
 *
 * Every one of these used to read `try { return await env.ASSETS.fetch(req) }
 * catch { …serve /index.html… }`. `env.ASSETS.fetch` does not throw on a miss —
 * it is documented as returning `Promise<Response>`, and an unmatched request
 * comes back as a RESPONSE whose status reflects `not_found_handling` (default
 * `none`, i.e. a plain 404). So the catch never ran, and the client-side-routing
 * fallback this adapter has advertised since it was written had never once
 * executed: a deep link to an SPA route returned Cloudflare's bare 404 instead
 * of the shell that would have routed it.
 *
 * Checking the status is the fix. The `try` is gone with it — there is no throw
 * to catch, and keeping one would only re-hide the next real error.
 *
 * Serving the shell for ANY 404, extension or not, matches Cloudflare's own
 * `not_found_handling = "single-page-application"` semantics ("when an incoming
 * request does not match a file in the assets directory, Workers will serve the
 * contents of /index.html with a 200 OK") rather than inventing a narrower rule
 * the platform does not have.
 */
function assetsWithSpaFallback(indent: string): string[] {
  return [
    `${indent}const assetResponse = await env.ASSETS.fetch(request)`,
    `${indent}if (assetResponse.status !== 404) return assetResponse`,
    `${indent}// SPA shell for client-side-routed paths. NOT a catch: env.ASSETS.fetch`,
    `${indent}// resolves with a 404 Response for a miss, it does not reject.`,
    `${indent}const url = new URL(request.url)`,
    `${indent}return env.ASSETS.fetch(new Request(new URL('/index.html', url.origin), request))`,
  ]
}

function generateWorkerEntry(): string {
  return [
    '// AUTO-GENERATED by @aihu/adapter-cloudflare — do not edit',
    '// Cloudflare Workers entry — SPA mode',
    '//',
    '// All page requests are served from the ASSETS binding (Cloudflare CDN).',
    '// For SSR mode use: cloudflare({ ssr: true })',
    '',
    'export default {',
    '  async fetch(request, env, _ctx) {',
    ...assetsWithSpaFallback('    '),
    '  },',
    '}',
  ].join('\n')
}

function generateSsrWorkerEntry(handlerSource: string): string {
  return [
    '// AUTO-GENERATED by @aihu/adapter-cloudflare — do not edit',
    '// Cloudflare Workers entry — SSR + static hybrid',
    '//',
    '// Route priority:',
    '//   1. SSR handler  — your aihu routes (API, agent-readiness, server-rendered pages)',
    '//   2. ASSETS       — pre-rendered static files served from Cloudflare CDN',
    '//   3. /index.html  — SPA shell fallback for client-side-routed pages',
    '',
    handlerSource,
    '',
    'export default {',
    '  async fetch(request, env, _ctx) {',
    '    // SSR: try your server routes first',
    '    const response = await handler(request, { env })',
    '    if (response.status !== 404) return response',
    '',
    '    // Static: pre-rendered pages and assets from ASSETS binding',
    ...assetsWithSpaFallback('    '),
    '  },',
    '}',
  ].join('\n')
}

/**
 * The `output: 'ssr'` worker wrapper, contributed INTO
 * `virtual:aihu-server-entry` rather than written to disk after the build.
 *
 * That relocation is the whole fix. The `ssr: true` path below emits its worker
 * as a string at `closeBundle`, outside the module graph, where it cannot
 * import `virtual:aihu-routes` — so `generateRoutesManifest` gives every route
 * a 404 placeholder and the worker renders nothing. Here `handler` is a real
 * `createServerRouter` over real route chunks, with the SSR child registry
 * already resolved.
 *
 * Route priority is unchanged from `generateSsrWorkerEntry`: SSR handler →
 * ASSETS (CDN edge) → `/index.html` (SPA shell).
 *
 * ## What `platform` is, and why it is `{ env, ctx }`
 *
 * `ServerRouter.handle` takes a second argument the framework never reads and
 * forwards, unchanged, to route loaders, the governed provider, the live
 * entitlement resolver and the session resolver. THE ADAPTER decides what goes
 * in it, because the framework must not know Cloudflare's shape — a Node or
 * Vercel host has entirely different ambient state.
 *
 * This adapter passes BOTH of the values a Worker's `fetch` receives, wrapped:
 *
 *   - `env` — the KV namespaces, D1 databases, R2 buckets, Durable Object
 *     stubs, queue producers and secrets. These exist ONLY per request; there
 *     is no module-scope handle a loader could have closed over, which is
 *     precisely why a Worker had no reachable data source before this.
 *   - `ctx` — the `ExecutionContext`, i.e. `waitUntil`. Passing `env` alone
 *     would have been tidier to read (`platform.DB`) but would have made
 *     background work — cache fills, analytics, revalidation — unreachable
 *     with no way to add it later without breaking every consumer.
 *
 * So a loader narrows once:
 *
 * ```ts
 * export const loader = async (params, { platform }) => {
 *   const { env, ctx } = platform as { env: Env; ctx: ExecutionContext }
 *   ctx.waitUntil(logHit(params))
 *   return env.DB.prepare('select * from posts where slug = ?').bind(params.slug).first()
 * }
 * ```
 *
 * NOTE the deliberate difference from the deprecated `generateSsrWorkerEntry`
 * above, which writes `handler(request, { env })`. That path wires
 * `createRequestRouter`, whose handler takes a `Request` and nothing else — so
 * its second argument has always been silently discarded. This one is real.
 */
function generateServerEntryWrapper({ handler }: ServerEntryContext): string {
  return [
    '// Cloudflare Workers wrapper — contributed by @aihu/adapter-cloudflare',
    '//   1. SSR handler  — real route modules, server-rendered, with bindings',
    '//   2. ASSETS       — client bundle + static files from the Cloudflare CDN',
    '//   3. /index.html  — SPA shell fallback for client-side-routed pages',
    'export default {',
    '  async fetch(request, env, ctx) {',
    // `{ env, ctx }` and not `env`: see the docblock. The framework treats this
    // as opaque, so the shape is this adapter's contract with its consumers.
    `    const response = await ${handler}(request, { env, ctx })`,
    '    if (response.status !== 404) return response',
    ...assetsWithSpaFallback('    '),
    '  },',
    '}',
  ].join('\n')
}

/**
 * Generate the source text of `routes-manifest.js`.
 *
 * @deprecated Superseded by `serverEntry` + `output: 'ssr'`. Kept so existing
 * `cloudflare({ ssr: true })` configs keep building; deletion is a follow-up.
 *
 * CORRECTION to what this docblock used to say. It blamed the 404 placeholders
 * on the page component living "behind a non-serializable `module()` thunk".
 * That is false, and it sent every prior fix attempt in the wrong direction:
 * `@aihu/app`'s `fileToRouteDefinition` builds
 * `module: () => Promise.resolve({ default: null })`, so there was never a
 * loadable module to serialize and no adapter-side fix was possible. Route
 * modules can only come from `virtual:aihu-routes`, from inside the build
 * graph — which is what `serverEntry` above does.
 *
 * The SSR worker's handler does `import routes from './routes-manifest.js'`
 * and then `createRequestRouter({ routes })`, so this module provides a default
 * export that is an array of route entries, each carrying a `pattern` and a
 * placeholder `handler` that 404s — letting the worker fall through to the
 * ASSETS binding (pre-rendered static pages).
 */
function generateRoutesManifest(routes: ReadonlyArray<ContextRoute>): string {
  const serialized = routes.map((route) => {
    const r = route as ContextRoute & { name?: string; ssr?: boolean }
    const entry: { pattern: string; segments: unknown; name?: string; ssr?: boolean } = {
      pattern: r.pattern,
      segments: r.segments,
    }
    if (typeof r.name === 'string') entry.name = r.name
    if (typeof r.ssr === 'boolean') entry.ssr = r.ssr
    return entry
  })

  return [
    '// AUTO-GENERATED by @aihu/adapter-cloudflare — do not edit',
    '// Routes manifest consumed by the SSR worker handler.',
    '//',
    '// `routes` is the default export and is wired into createRequestRouter via',
    '// `const _manifest = { routes }`. Each route carries a `pattern` (required',
    '// by the router) plus serialized metadata. The page component itself is not',
    '// serializable, so each route uses a placeholder handler that 404s, letting',
    '// the worker fall through to the ASSETS binding (pre-rendered static files).',
    '',
    'const notFound = () => new Response(null, { status: 404 })',
    '',
    `const routes = ${JSON.stringify(serialized, null, 2)}.map((route) => ({`,
    '  ...route,',
    '  handler: notFound,',
    '}))',
    '',
    'export default routes',
    '',
  ].join('\n')
}

/**
 * `main`/`[assets] directory` differ between the two shapes, and getting them
 * wrong is a security bug, not a config nit.
 *
 * Legacy (`ssr`/SPA string emission): `_worker.js` is written INTO the client
 * outDir, so `main` is relative to it and `directory = "."` is that same dir.
 *
 * `output: 'ssr'`: the server bundle lands in a SIBLING of the client outDir,
 * and the assets directory stays the client one. Pointing `[assets] directory`
 * at a root containing SSR chunks would let Cloudflare's ASSETS binding serve
 * server code on a public URL (D-2). Both are written relative to the project
 * root, since that is where wrangler.toml lives.
 *
 * ## `main` is DERIVED, not assumed
 *
 * This used to read `main = "dist-server/_worker.js"`, hardcoded, and the
 * comment above it asserted a "sibling `dist-server/`" as though that were
 * fixed. It is not, and had not been since `ssrOutDirFor` existed: `@aihu/app`
 * computes the SSR outDir from the client `build.outDir`, so a project
 * configuring `outDir: 'build'` gets its worker at `build-server/_worker.js`
 * while this file pointed wrangler at a `dist-server/_worker.js` that was never
 * written. `[assets] directory` was already parameterized; `main` was the half
 * that was not, so the failure was a deploy that could not find its entry
 * point. Same function, same input, one rule.
 *
 * ## Why `run_worker_first`
 *
 * Cloudflare's Workers Assets routing serves a MATCHING STATIC ASSET BEFORE it
 * invokes the Worker — `assets.run_worker_first` defaults to `false`. Combined
 * with `html_handling`, which defaults to `auto-trailing-slash` and therefore
 * maps `/` to `/index.html`, and with the fact that the SSR build writes that
 * very `index.html` into the client outDir this block points `[assets]` at, the
 * default configuration serves the STATIC SPA SHELL for `/` and never runs the
 * Worker. An `output: 'ssr'` site would have shipped with SSR silently off on
 * its most important route.
 *
 * `true` rather than a path list because SSR routes are dynamic and known only
 * to the router; there is no static set of prefixes to enumerate. The cost is
 * one Worker invocation for asset requests too, and the wrapper below is built
 * for exactly that: unmatched paths 404 out of the handler and are re-served
 * from `env.ASSETS`. That is the documented route priority this adapter has
 * always claimed (handler → ASSETS → index.html) and, before this line, never
 * actually had.
 *
 * Verified against Cloudflare's live documentation on 2026-08-08:
 * `run_worker_first` is the current, non-deprecated key, accepts `true|false`
 * or an array of glob patterns, and defaults to `false`.
 */
function generateWranglerToml(name: string, ssrOutput: boolean, clientOutDir: string): string {
  return `${[
    '# AUTO-GENERATED by @aihu/adapter-cloudflare',
    '# Edit this file to customize your Worker configuration.',
    '# Reference: https://developers.cloudflare.com/workers/wrangler/configuration/',
    '',
    `name = "${name}"`,
    ssrOutput ? `main = "${ssrOutDirFor(clientOutDir)}/_worker.js"` : 'main = "_worker.js"',
    'compatibility_date = "2024-01-01"',
    '',
    '[assets]',
    // Deliberately NOT the SSR outDir, and deliberately not a shared parent of
    // both: either would publish the server bundle.
    ssrOutput ? `directory = "${clientOutDir}"` : 'directory = "."',
    'binding = "ASSETS"',
    // SSR only. In SPA mode serving the asset first is the whole point, and a
    // Worker that only proxies ASSETS would be pure overhead.
    ...(ssrOutput
      ? [
          '# Without this, Cloudflare serves a matching static asset BEFORE running the',
          '# Worker — and html_handling maps "/" to the index.html in the assets',
          '# directory, so your home page would be the empty SPA shell and never be',
          '# server-rendered. Unmatched paths still fall through to ASSETS: the worker',
          '# 404s and re-serves them from the binding.',
          'run_worker_first = true',
        ]
      : []),
  ].join('\n')}\n`
}

/**
 * Cloudflare Workers / Pages adapter for aihu.
 *
 * Writes `_worker.js` to the Vite output directory and optionally creates
 * `wrangler.toml` in the project root (if absent).
 *
 * @example
 * // aihu.config.ts
 * import { defineConfig } from '@aihu/app'
 * import { cloudflare } from '@aihu/adapter-cloudflare'
 *
 * export default defineConfig({
 *   adapter: cloudflare({ name: 'my-worker' }),
 * })
 */
export function cloudflare(options?: CloudflareAdapterOptions): AihuAdapter {
  return {
    name: 'cloudflare',

    serverEntry: generateServerEntryWrapper,

    async adapt(context: AdapterContext): Promise<void> {
      const workerName = options?.name ?? readPackageJsonName(context.root) ?? 'aihu-app'
      const ssrOutput = context.config.output === 'ssr'

      // `output: 'ssr'` owns the worker entirely: it IS
      // `virtual:aihu-server-entry`, already written by the ssr environment's
      // build to the SSR outDir. Emitting a second `_worker.js` into the client
      // outDir here would shadow it with a static-only shell — and that shell is
      // what the ASSETS binding would serve. So the only thing left to do is
      // wrangler.toml.
      if (ssrOutput) {
        const wranglerPathSsr = resolvePath(context.root, 'wrangler.toml')
        // Both paths relative to the project root, because that is where
        // wrangler.toml lives and what its fields resolve against. `ssrOutDirFor`
        // is @aihu/app's own derivation — the SAME call the vite plugin makes to
        // decide where the ssr environment writes — so `main` names the file the
        // build actually produced even when `build.outDir` is not `dist`.
        const rel = relativePath(context.root, context.outDir).replace(/\\/g, '/') || '.'
        const serverRel = ssrOutDirFor(rel)
        if (options?.generateWrangler !== false && !existsSync(wranglerPathSsr)) {
          await context.writeFile(wranglerPathSsr, generateWranglerToml(workerName, true, rel))
          console.log(
            `[@aihu/adapter-cloudflare] Created wrangler.toml (name = "${workerName}", ` +
              `main = ${serverRel}/_worker.js, assets = ${rel}, run_worker_first = true)`,
          )
        }
        console.log(
          `[@aihu/adapter-cloudflare] output: 'ssr' — the worker is the build's own ` +
            `${serverRel}/_worker.js; no _worker.js emitted into ${context.outDir}`,
        )
        console.log(
          `[@aihu/adapter-cloudflare] Deploy with: wrangler deploy --config wrangler.toml`,
        )
        return
      }

      const ssrEnabled = options?.ssr === true

      // Default specifier the handler imports. Keep in sync with the file we
      // emit below so `import routes from '<spec>'` always resolves.
      const routesSpecifier = './routes-manifest.js'

      // Step 1 — In SSR mode, write routes-manifest.js BEFORE _worker.js.
      // The generated handler does `import routes from './routes-manifest.js'`,
      // so this file must exist for the worker to load.
      if (ssrEnabled) {
        const manifestRelPath = routesSpecifier.replace(/^\.\//, '')
        await context.emitFile(manifestRelPath, generateRoutesManifest(context.routes))
        console.log(
          `[@aihu/adapter-cloudflare] Wrote ${manifestRelPath} (${context.routes.length} route(s))`,
        )
      }

      // Step 2 — Write _worker.js
      const workerEntry = ssrEnabled
        ? generateSsrWorkerEntry(context.createHandlerSource({ routesSpecifier }))
        : generateWorkerEntry()
      await context.emitFile('_worker.js', workerEntry)
      console.log(
        `[@aihu/adapter-cloudflare] Wrote _worker.js (${ssrEnabled ? 'SSR hybrid' : 'SPA'} mode)`,
      )

      // Step 3 — Write wrangler.toml (only if absent, never overwrites)
      const wranglerPath = resolvePath(context.root, 'wrangler.toml')
      if (options?.generateWrangler !== false && !existsSync(wranglerPath)) {
        const toml = generateWranglerToml(workerName, false, '.')
        await context.writeFile(wranglerPath, toml)
        console.log(`[@aihu/adapter-cloudflare] Created wrangler.toml (name = "${workerName}")`)
      }

      console.log(`[@aihu/adapter-cloudflare] Build complete → ${context.outDir}`)
      console.log(`[@aihu/adapter-cloudflare] Deploy with: wrangler deploy --config wrangler.toml`)
    },
  }
}
